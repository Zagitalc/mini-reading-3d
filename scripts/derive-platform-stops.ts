import {readFile,writeFile} from 'node:fs/promises';
import {derivePlatformStops} from '../shared/station-platforms';
import {STATION_PLATFORMS} from '../shared/landmark-components';
// Rewrites shared/reading-platforms.ts from the platform footprints already in public/data/landmark-components.json.
const {components}=JSON.parse(await readFile('public/data/landmark-components.json','utf8'));
const stops=derivePlatformStops(components.filter((c:{id:string})=>STATION_PLATFORMS.includes(c.id)));
const rows=Object.keys(stops).sort((a,b)=>Number(a)-Number(b)).map(ref=>` '${ref}':${JSON.stringify(stops[ref])},`).join('\n');
await writeFile('shared/reading-platforms.ts',`import type {PlatformStop} from './station-platforms';\n// Generated by scripts/derive-platform-stops.ts from the Reading station platform footprints; tests keep it in step with them.\nexport const READING_PLATFORMS:Record<string,PlatformStop>={\n${rows}\n};\n`);
console.log(`${Object.keys(stops).length} platforms written`);
